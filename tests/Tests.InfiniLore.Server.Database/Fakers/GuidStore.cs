[AttributeUsage(AttributeTargets.Field)]
public class GuidAttribute(string guid) : Attribute {
    public Guid Value { get; } = Guid.Parse(guid);
}

public static class EnumExtensions {
    public static Guid ToGuid(this GuidStore value) {
        var attribute = value.GetType()
            .GetField(value.ToString())
            ?.GetCustomAttribute<GuidAttribute>();
        return attribute?.Value ?? throw new InvalidOperationException("GUID not defined.");
    }
}
